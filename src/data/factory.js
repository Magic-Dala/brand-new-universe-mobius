// Abandoned Halloween factory — INTERIOR scene layout (separate from the ring city).
// Pure data (no three.js) so tests can check it. Interior-local frame: origin = floor centre,
// +X = east, −Z = north, +Y = up. Hall 22 m (E–W) × 36 m (N–S), roof (truss bottom) 14 m.
// The interior is placed at INTERIOR.origin in world space; the city is unloaded while it is
// active, so the two never render or update at the same time.

import { FACTORY_LAYOUT as L } from './factoryLayout.gen.js'; // generated by tools/blender/build_factory.py

const W = L.size.w, D = L.size.d, H = L.size.h;
const KIND_H = { machine: 3.0, crates: 1.6, barrel: 1.0, stairs: 6.0, rack: 3.0, lockers: 1.9, debris: 2.2 };

export const INTERIOR = {
  origin: [0, -500, 0], // world position of the interior-local origin (far below the lower deck)
  size: { w: W, d: D, h: H },
  wallPad: 0.45, // teleport keeps this far from the walls
  // roof breach the player falls through (matches the exterior roof section of factory C, SW)
  breach: { ...L.breach },
  // closed plenum above the hole (modelled in Blender): darkness, cables — the city is never visible
  plenum: { h: 6 },
  // spawn under the breach, clear of the SW crash debris and the machines
  spawn: { pos: [L.spawn[0], 0, L.spawn[1]], yaw: Math.PI * 0.1 }, // facing roughly north (toward the boss zone)
  // separate interior blue circle (PLAYER START, south-centre)
  arenaCircle: { pos: [L.arenaCircle[0], 0, L.arenaCircle[1]], radius: L.arenaCircle[2] },
  // far-north boss hover zone (the arcade battle's boss home)
  bossHover: [...L.bossHover],
  // boss entry: down through the breach (engine overhead), short landing hover, then north
  bossEntry: [[L.breach.x, 21, L.breach.z], [L.breach.x, 10.5, L.breach.z - 2], [-2.5, 8.0, 1.5], [...L.bossHover]],
  // clear central combat floor between the side bays (painted yellow lines in the model)
  combatFloor: { x0: -6.3, x1: 6.3, z0: -14, z1: 11.4 }, // south of it: PLAYER START + the SW debris
  catwalkY: 6.0,
  craneY: 9.2,
  trussY: 11.6,
  // obstacles on the floor (teleport blockers, minimap): machines, crates, barrels, stairs, racks, debris
  blockers: L.blockers.map((b) => ({ x0: b.x0, x1: b.x1, z0: b.z0, z1: b.z1, h: KIND_H[b.kind] || 2, kind: b.kind, name: b.name })),
  lamps: L.lamps, // [x, y, z, purple?] light sources of the Blender scene (glow halos, light cones)
  pumpkins: L.pumpkins, // [x, y, z, scale]
};

/** Teleport surface (interior-local): the floor minus the blockers (padded). */
export function interiorSurface(pad = 0.35) {
  const { w, d } = INTERIOR.size, wp = INTERIOR.wallPad;
  return {
    x0: -w / 2 + wp, x1: w / 2 - wp, z0: -d / 2 + wp, z1: d / 2 - wp,
    blockers: INTERIOR.blockers.map((b) => ({ x0: b.x0 - pad, x1: b.x1 + pad, z0: b.z0 - pad, z1: b.z1 + pad })),
  };
}
/** Smallest distance (xz) from a point to any blocker rect (0 if inside). */
export function clearance(x, z) {
  let m = Infinity;
  for (const b of INTERIOR.blockers) {
    const dx = Math.max(b.x0 - x, 0, x - b.x1), dz = Math.max(b.z0 - z, 0, z - b.z1);
    m = Math.min(m, Math.hypot(dx, dz));
  }
  return m;
}
/** interior-local → world */
export const interiorToWorld = (x, y, z) => [x + INTERIOR.origin[0], y + INTERIOR.origin[1], z + INTERIOR.origin[2]];
