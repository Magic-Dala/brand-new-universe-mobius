// Dala City modules (街區模組) — pure data, no three.js.
//
// A module is one 72 × 72 m cell centred on a 4-way intersection (avenue along local z, cross street
// along local x, both 24 m between building lines). Local frame: x = right, z = back, travel direction =
// local −Z ("forward"). The four corner blocks (24 × 24 m each, NW / NE / SW / SE) are filled from
// VALIDATED lot templates; every lot that fronts a street carries fixed swing anchors on that face.
// Cells line up edge to edge, so streets and the 48 m city blocks continue across modules.
//
// Module definition (MODULES[kind]): theme, local exits ('N' forward / 'W' left / 'E' right), boss path,
// event mounts, the modules that may follow (next) and the appearance variants. The content of a module
// (buildings, colliders, anchors, props, boss path, mounts, checkpoint) is generated by moduleContent()
// in the local frame (deterministic: kind + variant + seed) and placed in the world by placeContent().
import { CITY_CFG, floorHOf } from './cityConfig.js';
import { mulberry32, hashInt } from './box.js';

const S = CITY_CFG.cell, HALF = S / 2, SL = CITY_CFG.street / 2; // 36, 12
const QB = HALF - SL; // corner block size 24
export const STYLE = { redBrick: 0, brownBrick: 1, creamBrick: 2, limestone: 3, glass: 4, darkGlass: 5, industrial: 6, home: 1 };
const FAMILY = ['res', 'res', 'res', 'com', 'glass', 'glass', 'ind'];
const THEME_STYLES = {
  res: [STYLE.redBrick, STYLE.brownBrick, STYLE.redBrick, STYLE.creamBrick, STYLE.brownBrick],
  com: [STYLE.limestone, STYLE.glass, STYLE.limestone, STYLE.darkGlass, STYLE.creamBrick, STYLE.glass],
  ind: [STYLE.industrial, STYLE.industrial, STYLE.brownBrick],
};
const TEMPLATES = {
  // quadrant-local: u = metres from the avenue line outward, v = metres from the cross-street line outward
  one: [[0, 24, 0, 24]],
  two: [[0, 24, 0, 12], [0, 24, 12, 24]],
  three: [[0, 24, 0, 8], [0, 24, 8, 16], [0, 24, 16, 24]],
  twoU: [[0, 12, 0, 24], [12, 24, 0, 24]],
  corner3: [[0, 12, 0, 12], [0, 12, 12, 24], [12, 24, 0, 24]],
};
const THEME_TPL = { res: ['three', 'two', 'corner3', 'three', 'twoU'], com: ['one', 'two', 'twoU', 'one'], ind: ['two', 'one', 'twoU'] };
const QUADS = { NW: [-1, -1], NE: [1, -1], SW: [-1, 1], SE: [1, 1] };

/**
 * Module kinds. exits: local exit edges ('N' = forward, 'W' = left, 'E' = right).
 * next: kinds allowed to follow (the route generator also applies the endless rules).
 */
export const MODULES = {
  start: { label: '起始住宅街區 / home block', theme: 'res', exits: ['N'], next: ['straightRes', 'straightCom'], variants: 1 },
  straightRes: { label: '直線住宅街區 / residential straight', theme: 'res', exits: ['N'], next: ['straightRes', 'straightCom', 'cross', 'turnL', 'turnR'], variants: 4 },
  straightCom: { label: '直線商業街區 / commercial straight', theme: 'com', exits: ['N'], next: ['straightRes', 'straightCom', 'cross', 'turnL', 'turnR'], variants: 4 },
  cross: { label: '十字路口 / crossroads (choose)', theme: 'mix', exits: ['N', 'W', 'E'], next: ['straightRes', 'straightCom'], variants: 3 },
  turnL: { label: '左轉街區 / left turn', theme: 'mix', exits: ['W'], next: ['straightRes', 'straightCom'], variants: 3 },
  turnR: { label: '右轉街區 / right turn', theme: 'mix', exits: ['E'], next: ['straightRes', 'straightCom', 'factory'], variants: 3 },
  factory: { label: '工廠事件街區 / factory event block', theme: 'ind', exits: ['N'], next: ['factoryExit'], variants: 1, deadEnd: true },
  factoryExit: { label: '工廠出口銜接街區 / factory exit', theme: 'res', exits: ['N'], next: ['straightRes', 'straightCom'], variants: 1 },
  filler: { label: '背景街廓 / side block', theme: 'auto', exits: [], next: [], variants: 4 },
};

// ---------------------------------------------------------------- headings / transforms
/** heading 0 = north (−Z), 1 = east (+X), 2 = south, 3 = west. Grid step per heading (i, j); north = j − 1. */
export const STEP = [[0, -1], [1, 0], [0, 1], [-1, 0]];
export const exitHeading = (heading, exit) => (heading + (exit === 'E' ? 1 : exit === 'W' ? 3 : 0)) % 4;
export const yawOfHeading = (h) => -h * Math.PI / 2;
/** Tile transform: local (x, z) → world. */
export function transformOf(cx, cz, heading) {
  const yaw = yawOfHeading(heading), cos = Math.cos(yaw), sin = Math.sin(yaw);
  const c = Math.round(cos), s = Math.round(sin); // exact for multiples of 90°
  return { cx, cz, yaw, cos: c, sin: s, heading };
}
export const toWorldXZ = (T, lx, lz) => [T.cx + lx * T.cos + lz * T.sin, T.cz - lx * T.sin + lz * T.cos];
export const dirToWorld = (T, nx, nz) => [nx * T.cos + nz * T.sin, -nx * T.sin + nz * T.cos];

// ---------------------------------------------------------------- story overrides (fixed route appearance)
// flyIn / flyOut: Green Maniac + swing height through the tile; minH / maxH: building heights (m)
export const STORY_TILES = [
  { kind: 'start', flyIn: 77, flyOut: 75 },
  { kind: 'straightRes', variant: 1, flyIn: 75, flyOut: 73, minH: 62, maxH: 100 },
  { kind: 'straightCom', variant: 0, flyIn: 73, flyOut: 71, minH: 70, maxH: 128 },
  { kind: 'straightRes', variant: 2, flyIn: 71, flyOut: 68, minH: 58, maxH: 96 },
  { kind: 'straightCom', variant: 3, flyIn: 68, flyOut: 64, minH: 64, maxH: 120 },
  { kind: 'straightRes', variant: 0, flyIn: 64, flyOut: 60, minH: 54, maxH: 90 },
  { kind: 'turnR', variant: 0, flyIn: 60, flyOut: 54, minH: 56, maxH: 118 },
  { kind: 'factory', flyIn: 52, flyOut: 31 },
];

// ---------------------------------------------------------------- factory / home footprints (module-local)
export const FACTORY_LOCAL = { lx: 0, lz: -31, hx: 12, hz: 19, h: 21.6 }; // 24 × 38, across the avenue end (door = local −Z face)
export const HOME_LOCAL = { lx: 0, lz: 24, hx: 12, hz: 12, h: 28 * 3.6 }; // home tower A on the avenue's south stub (window = local −Z face)

// ---------------------------------------------------------------- generation helpers
function quadrantLots(q, tpl) {
  const [sx, sz] = QUADS[q];
  return TEMPLATES[tpl].map(([u0, u1, v0, v1], k) => {
    const x0 = sx * (SL + u0), x1 = sx * (SL + u1), z0 = sz * (SL + v0), z1 = sz * (SL + v1);
    const faces = [];
    if (u0 === 0) faces.push({ f: sx > 0 ? '-x' : '+x', w: v1 - v0, street: 'avenue' });
    if (v0 === 0) faces.push({ f: sz > 0 ? '-z' : '+z', w: u1 - u0, street: 'cross' });
    return { q, k, lx: (x0 + x1) / 2, lz: (z0 + z1) / 2, hx: Math.abs(x1 - x0) / 2, hz: Math.abs(z1 - z0) / 2, faces, corner: u0 === 0 && v0 === 0 };
  });
}
const FACE_N = { '+x': [1, 0], '-x': [-1, 0], '+z': [0, 1], '-z': [0, -1] };

function themeOfQuadrant(theme, q, r) {
  if (theme === 'mix') return r() < 0.5 ? 'res' : 'com';
  if (theme === 'auto') return r() < 0.62 ? 'res' : 'com';
  return theme;
}

/**
 * Generate a module's content in its LOCAL frame (cached by callers).
 * opts: { kind, variant, seed, flyIn, flyOut, minH, maxH, tag, exit (cross: chosen exit) }
 */
export function moduleContent(opts) {
  const { kind, variant = 0, seed = 1, tag = 'm' } = opts;
  const M = MODULES[kind] || MODULES.filler;
  const r = mulberry32(hashInt(seed, kind.length * 131 + variant * 17 + 7));
  const fly = { in: opts.flyIn ?? 55, out: opts.flyOut ?? opts.flyIn ?? 55 };
  const buildings = [];
  const special = [];
  if (kind === 'start') special.push({ id: 'A', role: 'home', ...HOME_LOCAL, style: STYLE.home, family: 'res', faces: [{ f: '-z', w: 24, street: 'cross' }], seed: 911 });
  if (kind === 'factory') special.push({ id: 'C', role: 'factory', ...FACTORY_LOCAL, style: STYLE.industrial, family: 'ind', faces: [], seed: 4242 });

  for (const q of Object.keys(QUADS)) {
    let qTheme = themeOfQuadrant(M.theme, q, r);
    if (kind === 'factory' && (q === 'NW' || q === 'NE')) qTheme = 'ind';
    const tplList = THEME_TPL[qTheme] || THEME_TPL.res;
    const tpl = tplList[(variant + Math.floor(r() * tplList.length)) % tplList.length];
    const lots = quadrantLots(q, tpl);
    const styles = THEME_STYLES[qTheme];
    const fam0 = qTheme;
    // heights (m): theme ranges, story overrides, corner lots a bit taller
    const range = { res: [20, 58], com: [42, 132], ind: [13, 34] }[qTheme] || [20, 60];
    let lo = opts.minH ?? range[0], hi = opts.maxH ?? range[1];
    if (kind === 'factory') { lo = q[0] === 'N' ? 14 : 28; hi = q[0] === 'N' ? 30 : 52; }
    if (kind === 'start' && q[0] === 'N') { lo = 84; hi = 122; } // the first anchors seen from the window (above it)
    // turns: the inner corner (swung around) and the block lining the new street stay tall
    if (kind === 'turnR' || kind === 'turnL') { const key = kind === 'turnR' ? (q === 'SE' || q === 'NE') : (q === 'SW' || q === 'NW'); if (key) lo = Math.max(lo, opts.minH ?? 52); }
    const qStyle = styles[Math.floor(r() * styles.length)];
    for (const lot of lots) {
      let style = r() < 0.7 ? qStyle : styles[Math.floor(r() * styles.length)];
      if (qTheme === 'res' && (style === STYLE.glass || style === STYLE.darkGlass)) style = STYLE.brownBrick;
      const family = FAMILY[style];
      const fh = floorHOf(family);
      let h = lo + (hi - lo) * Math.pow(r(), lot.corner ? 0.7 : 1.15);
      if (style === STYLE.glass || style === STYLE.darkGlass) h = Math.max(h, Math.min(hi, lo + (hi - lo) * 0.6));
      h = Math.max(fh * 4, Math.round(h / fh) * fh);
      buildings.push({ ...lot, h, style, family, seed: hashInt(seed, buildings.length * 7919 + 3) >>> 0, tierK: 0 });
    }
    // validated: every corner block keeps at least one building tall enough for swinging anchors
    const need = kind === 'factory' ? (q[0] === 'N' ? 14 : 26) : Math.max(30, (opts.minH ?? 30));
    const qb = buildings.filter((b) => b.q === q);
    if (!qb.some((b) => b.h >= need)) { const c = qb.find((b) => b.corner) || qb[0]; c.h = Math.ceil(need / floorHOf(c.family)) * floorHOf(c.family); }
  }
  // remove lots that overlap the special footprints (home tower / factory)
  const overlap = (a, b) => Math.abs(a.lx - b.lx) < a.hx + b.hx - 0.01 && Math.abs(a.lz - b.lz) < a.hz + b.hz - 0.01;
  const list = buildings.filter((b) => !special.some((s) => overlap(b, s)));
  list.push(...special);

  // tiers (setbacks) for tall limestone / glass towers, tint, lit-window fraction
  for (const b of list) {
    const rr = mulberry32(b.seed ^ 0x51ab);
    b.tiers = [{ hx: b.hx, hz: b.hz, y0: 0, y1: b.h }];
    if (!b.role && (b.style === STYLE.limestone || b.style === STYLE.glass) && b.h > 70 && b.hx > 7 && b.hz > 7 && rr() < 0.75) {
      const cut = Math.round((b.h * (0.55 + rr() * 0.18)) / floorHOf(b.family)) * floorHOf(b.family);
      const inset = b.style === STYLE.limestone ? 2.6 : 1.8;
      b.tiers = [{ hx: b.hx, hz: b.hz, y0: 0, y1: cut }, { hx: b.hx - inset, hz: b.hz - inset, y0: cut, y1: b.h }];
      if (b.style === STYLE.limestone && b.h > 100 && rr() < 0.6) {
        const cut2 = Math.round((cut + (b.h - cut) * 0.6) / floorHOf(b.family)) * floorHOf(b.family);
        b.tiers[1].y1 = cut2; b.tiers.push({ hx: b.hx - inset * 2, hz: b.hz - inset * 2, y0: cut2, y1: b.h });
      }
    }
    const tv = 0.9 + rr() * 0.16;
    b.tint = [tv * (0.97 + rr() * 0.06), tv * (0.95 + rr() * 0.06), tv * (0.93 + rr() * 0.08)];
    b.lit = b.family === 'res' ? 0.1 + rr() * 0.14 : b.family === 'glass' ? 0.05 + rr() * 0.08 : b.family === 'ind' ? 0.08 : 0.08 + rr() * 0.12; // sunset: only some rooms lit
    b.shops = !b.role && b.faces.length > 0 && b.family !== 'ind' && rr() < (b.family === 'com' ? 0.85 : 0.6);
    b.shadowLine = 18 + rr() * 22; // street-canyon shadow height (warm sun only above it)
    b.id = b.role ? b.id : `${tag}.${b.q}${b.k}`;
  }

  // ---------------- anchors (fixed swing points on street-facing faces), local frame
  const A = CITY_CFG.anchors;
  const anchors = [];
  const blocked = (x, y, z) => list.some((b) => b.tiers.some((t) => y >= t.y0 && y <= t.y1 && Math.abs(x - b.lx) <= t.hx && Math.abs(z - b.lz) <= t.hz));
  const clear = (x, y, z, nx, nz) => A.clear.every((d) => !blocked(x + nx * d, y, z + nz * d));
  for (const b of list) {
    if (b.h < A.minRoofH || b.role) continue; // home tower / factory: named anchors below
    for (const face of b.faces) {
      const [nx, nz] = FACE_N[face.f];
      const top = b.tiers.find((t) => t.y0 === 0); // the front tier
      const half = nx ? top.hz : top.hx;
      const offs = face.w >= 20 ? [-half / 2, half / 2] : [0];
      const ys = [['R', top.y1 - A.roofDrop]];
      if (b.h >= A.midMinH) ys.push(['M', Math.round(b.h * 0.6 * 10) / 10]);
      for (const [yk, y] of ys) {
        offs.forEach((o, i) => {
          const x = b.lx + (nx ? nx * (top.hx + A.out) : o), z = b.lz + (nz ? nz * (top.hz + A.out) : o);
          if (!clear(x, y, z, nx, nz)) return;
          anchors.push({ id: `${b.id}.${face.f}${yk}${i}`, building: b.id, kind: yk === 'R' ? 'roof' : 'facade', lp: [x, y, z], ln: [nx, 0, nz] });
        });
      }
    }
    if (b.h >= A.mastMinH && !b.role) { b.mast = true; anchors.push({ id: `${b.id}.mast`, building: b.id, kind: 'mast', lp: [b.lx, b.h + 10.5, b.lz], ln: [0, 1, 0] }); }
  }
  if (kind === 'start') { // the home tower's north roof edge (as in v0.9–0.19)
    const H = HOME_LOCAL;
    anchors.push({ id: 'A-N-ROOF-W', building: 'A', kind: 'roof', lp: [H.lx - 8, H.h - 1, H.lz - H.hz - A.out], ln: [0, 0, -1] });
    anchors.push({ id: 'A-N-ROOF-E', building: 'A', kind: 'roof', lp: [H.lx + 9, H.h - 1, H.lz - H.hz - A.out], ln: [0, 0, -1] });
  }
  if (kind === 'factory') { // smokestack on the factory roof (box-local (7.5, 14), 20 m high) → see layout FACTORY_EXT.stack
    const F = FACTORY_LOCAL; // box frame = module frame (door = local −Z face); stack at box (7.5, 14), 20 m above the roof
    anchors.push({ id: 'C-STACK', building: 'C', kind: 'mast', lp: [F.lx + 7.5, F.h + 20.3, F.lz + 14], ln: [0, 1, 0] });
  }

  // ---------------- props (rooftop / facade / street), local frame
  const props = { waterTowers: [], roofBoxes: [], fireEscapes: [], lamps: [], trees: [], masts: [] };
  for (const b of list) {
    if (b.role) continue;
    const rr = mulberry32(b.seed ^ 0xdec0), t = b.tiers[b.tiers.length - 1];
    const inner = (m) => [b.lx + (rr() - 0.5) * Math.max(0, t.hx * 2 - m), b.lz + (rr() - 0.5) * Math.max(0, t.hz * 2 - m)];
    if (b.family === 'res' && b.h < 80 && rr() < 0.6) { const [x, z] = inner(7); props.waterTowers.push([x, t.y1, z, 0.75 + rr() * 0.4, rr() * 6.28]); }
    if (rr() < 0.85) { const [x, z] = inner(5); props.roofBoxes.push([x, t.y1, z, 2.4 + rr() * 2, 2.2 + rr() * 1.4, 2.4 + rr() * 2, 0]); }
    if (b.family !== 'res' && rr() < 0.8) for (let k = 0; k < 2; k++) { const [x, z] = inner(4); props.roofBoxes.push([x, t.y1, z, 2.2, 1.2, 1.6, 1]); }
    if (b.mast) props.masts.push([b.lx, t.y1, b.lz, 11]);
    if (b.family === 'res' && b.h >= 14) {
      for (const face of b.faces) {
        if (face.w < 8 || rr() < 0.25) continue;
        const [nx, nz] = FACE_N[face.f], w = 3.2;
        const half = (nx ? b.hz : b.hx) - w / 2 - 1;
        const o = (rr() - 0.5) * 2 * Math.max(0, half);
        props.fireEscapes.push([b.lx + (nx ? nx * (b.hx + 0.55) : o), b.lz + (nz ? nz * (b.hz + 0.55) : o), nx, nz, w, 4.2, b.h - 2.4]);
      }
    }
  }
  // street lamps + trees on the sidewalks (not inside the home tower / factory footprints)
  const insideSpecial = (x, z) => special.some((s) => Math.abs(x - s.lx) < s.hx + 0.5 && Math.abs(z - s.lz) < s.hz + 0.5);
  const tr = mulberry32(hashInt(seed, 0x7ee5));
  const pTree = M.theme === 'com' ? 0.3 : M.theme === 'ind' ? 0.12 : 0.6;
  for (const side of [-1, 1]) {
    for (const along of [-30, -18, 18, 30]) {
      // avenue sidewalks (x = ±9.6), cross-street sidewalks (z = ±9.6); lamp heads lean over the road
      for (const [x, z, nx, nz] of [[side * 9.6, along, -side, 0], [along, side * 9.6, 0, -side]]) {
        if (insideSpecial(x, z)) continue;
        if (Math.abs(along) === 18) props.lamps.push([x, z, nx, nz]);
        else if (tr() < pTree) props.trees.push([x + (nx ? 0 : (tr() - 0.5) * 3), z + (nz ? 0 : (tr() - 0.5) * 3), 0.8 + tr() * 0.45]);
      }
    }
  }

  // ---------------- boss path (local, with heights) for every exit + mounts + checkpoint
  const paths = {}; for (const e of (M.exits.length ? M.exits : ['N'])) paths[e] = modulePath(kind, e, fly);
  const mounts = {};
  if (kind === 'turnR' || kind === 'turnL' || kind === 'cross') mounts.turnArrow = [0, fly.in + 7, 0];
  if (kind === 'factoryExit') { mounts.exitSpawn = [0, 0, 17]; mounts.bossExit = [[0, 4.5, 23], [0, 14, 4], [0, 34, -20], [0, 48, -HALF]]; }
  // checkpoint: a cling spot on an avenue face in the entry half (a street-facing wall the player can hang on)
  let checkpoint = null;
  if (kind === 'factory') checkpoint = { kind: 'factoryRoof' };
  else if (kind === 'factoryExit') checkpoint = { kind: 'ground', lp: [0, 0, 17], ln: [0, 0, -1] };
  else if (kind !== 'start') {
    const cand = list.filter((b) => !b.role && b.faces.some((f) => f.street === 'avenue') && b.lz > 0 && b.h >= 26).sort((a, b) => b.h - a.h)[0]
      || list.filter((b) => !b.role && b.faces.length && b.h >= 20).sort((a, b) => b.h - a.h)[0];
    if (cand) {
      const face = cand.faces.find((f) => f.street === 'avenue') || cand.faces[0], [nx, nz] = FACE_N[face.f];
      const y = Math.min(cand.h - 3, Math.max(20, Math.min(fly.in - 2, cand.h * 0.62)));
      checkpoint = { kind: 'cling', building: cand.id, lp: [cand.lx + nx * (cand.hx + 0.6), y, cand.lz + nz * (cand.hz + 0.6)], ln: [nx, 0, nz] };
    }
  }
  return { kind, variant, seed, buildings: list, anchors, props, paths, mounts, checkpoint, fly };
}

/**
 * Boss / route centre line through a module (local [x, y, z] points, entry edge → exit edge), with the
 * flight height interpolated from fly.in to fly.out. exit: 'N' | 'E' | 'W'.
 */
export function modulePath(kind, exit = 'N', fly = { in: 55, out: 55 }) {
  let pts;
  if (kind === 'factory') pts = [[0, HALF], [0, 8], [0, -20]];
  else if (kind === 'start') pts = [[6, 8], [2, -14], [0, -HALF]];
  else if (kind === 'factoryExit') pts = [[0, 20], [0, 0], [0, -HALF]];
  else if (exit === 'E' || exit === 'W') {
    const s = exit === 'E' ? 1 : -1, R = 11;
    pts = [[0, HALF], [0, R]];
    for (let k = 1; k < 6; k++) { const a = (k / 6) * Math.PI / 2; pts.push([s * (R - R * Math.cos(a)), R - R * Math.sin(a)]); }
    pts.push([s * R, 0], [s * HALF, 0]);
  } else pts = [[0, HALF], [0, 0], [0, -HALF]];
  let L = 0; const seg = [0];
  for (let i = 1; i < pts.length; i++) { L += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]); seg.push(L); }
  return pts.map(([x, z], i) => [x, fly.in + (fly.out - fly.in) * (seg[i] / L), z]);
}

/** Lot / style statistics of a module (tests, docs). */
export function moduleSummary(c) {
  return { buildings: c.buildings.length, anchors: c.anchors.length, maxH: Math.max(...c.buildings.map((b) => b.h)), props: Object.fromEntries(Object.entries(c.props).map(([k, v]) => [k, v.length])) };
}
