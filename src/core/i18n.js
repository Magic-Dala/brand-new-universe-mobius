const LS_KEY = 'mobius.lang';
let lang = (() => {
  try {
    const s = localStorage.getItem(LS_KEY);
    if (s && STR[s]) return s;
  } catch { /* storage blocked */ }
  const nav = (navigator.language || '').toLowerCase();
  return nav.startsWith('zh') ? 'zh-Hant' : 'en';
})();
const listeners = new Set();

export const getLang = () => lang;
export function setLang(l) {
  if (!STR[l] || l === lang) return;
  lang = l;
  try { localStorage.setItem(LS_KEY, l); } catch { /* ignore */ }
  document.documentElement.lang = l === 'zh-Hant' ? 'zh-Hant' : 'en';
  listeners.forEach((f) => f(l));
}
export const onLangChange = (f) => (listeners.add(f), () => listeners.delete(f));

/** Translate key with {placeholders}. Character names auto-fill {hero}/{boss}/{jet}. */
export function t(key, vars) {
  const table = STR[lang];
  let s = table[key] ?? STR.en[key] ?? key;
  if (s.includes('{')) {
    const v = { hero: table['char.hero'], boss: table['char.boss'], jet: table['char.jet'], city: table['place.city'], ...vars };
    s = s.replace(/\{(\w+)\}/g, (m, k) => (v[k] !== undefined ? String(v[k]) : m));
  }
  return s;
}
